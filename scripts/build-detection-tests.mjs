#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { checkout } from './fetch-torture-sources.mjs';
const pins = JSON.parse(fs.readFileSync('tests/torture/pins.json', 'utf8')).suites;
const sha256 = b => crypto.createHash('sha256').update(b).digest('hex');
const outDir = 'tests/assets/torture';
fs.mkdirSync(outDir, { recursive: true });
const manifestPath = path.join(outDir, 'MANIFEST.json');
const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : { version: 1, binaries: [] };
function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8', timeout: 900000, maxBuffer: 32 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(' ')} failed (${r.status}):\n${r.stderr || r.stdout || r.error}`);
  return r.stdout;
}
function add(name, file, suite, args, env = {}) {
  const bytes = fs.readFileSync(file);
  const pe = bytes.readUInt32LE(0x3c);
  if (bytes.readUInt16LE(pe + 4) !== 0x8664 || bytes.readUInt16LE(pe + 24) !== 0x20b) throw new Error(`${file} is not PE32+ x64`);
  const target = path.join(outDir, name);
  fs.copyFileSync(file, target);
  const entry = { name, path: target, suite, sha256: sha256(bytes), bytes: bytes.length, sourceRevision: pins[suite].revision, args, env, origin: 'upstream-source-unmodified' };
  manifest.binaries = manifest.binaries.filter(b => b.name !== name).concat(entry);
  console.log(`[detection-build] ${name} PE32+ ${bytes.length} bytes sha256=${entry.sha256}`);
}
const only = process.argv.includes('--only') ? process.argv[process.argv.indexOf('--only') + 1] : 'all';
if (only === 'all' || only === 'al-khaser') {
  if (process.platform !== 'win32') throw new Error('al-khaser requires the upstream MSVC x64 build on Windows CI (MASM + Windows SDK); use the torture workflow windows job. No substitute binary is accepted.');
  const pin = pins['al-khaser'];
  checkout(pin.repository, pin.revision, pin.path);
  const msbuild = process.env.PORTHOLE_MSBUILD || 'msbuild';
  run(msbuild, ['al-khaser/al-khaser.vcxproj', '/m', '/p:Configuration=Release', '/p:Platform=x64', '/p:PlatformToolset=v143'], pin.path);
  const candidates = ['al-khaser/al-khaser_x64.exe', 'al-khaser/x64/Release/al-khaser.exe', 'al-khaser/x64/Release/al-khaser_x64.exe'];
  const exe = candidates.map(f => path.join(pin.path, f)).find(f => fs.existsSync(f));
  if (!exe) throw new Error(`MSBuild produced no known x64 executable: ${candidates.join(', ')}`);
  add('al-khaser.exe', exe, 'al-khaser', ['--sleep', '1'], {});
}
if (only === 'all' || only === 'pafish') {
  const pin = pins.pafish;
  checkout(pin.repository, pin.revision, pin.path);
  const zig = process.env.PORTHOLE_ZIG || (fs.existsSync('/home/user/.cache/porthole-tools/ziglang/zig') ? '/home/user/.cache/porthole-tools/ziglang/zig' : 'zig');
  const version = run(zig, ['version']).trim();
  if (!version.startsWith('0.13.')) throw new Error(`pafish build requires Zig 0.13.x, got ${version}`);
  const src = path.join(pin.path, 'pafish');
  const sources = ['main','common','utils','debuggers','sandboxie','vbox','gensandbox','wine','vmware','qemu','cpu','bochs','rtt'].map(n => `${n}.c`);
  // Upstream resource script is generated by its IDE; the icon resource is optional to execution.
  // Compile the exact C sources and link the same x64 libraries as Makefile64.linux.
  run(zig, ['cc', '-target', 'x86_64-windows-gnu', '-O0', '-Wno-cast-function-type', ...sources,
    '-lws2_32', '-liphlpapi', '-lsetupapi', '-lmpr', '-lole32', '-lwbemuuid', '-loleaut32', '-lwsock32',
    '-Wl,--subsystem,console', '-o', path.resolve(outDir, 'pafish64.exe')], src);
  add('pafish64.exe', path.join(outDir, 'pafish64.exe'), 'pafish', [], {});
}
manifest.generatedAt = new Date().toISOString();
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
